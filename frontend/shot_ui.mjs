import { chromium } from 'playwright';
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1500, height: 950 }, deviceScaleFactor: 2, locale: 'zh-CN' });
const p = await ctx.newPage();
await p.goto('http://189.105.70.85:20000/', { waitUntil: 'networkidle', timeout: 60000 });
await p.fill('input[autocomplete="username"]', 'eu6qSQvOwL');
await p.fill('input[autocomplete="current-password"]', '3uplqkCMq4');
await p.click('button[type="submit"]');
await p.waitForTimeout(4000);
await p.goto('http://189.105.70.85:20000/panel/inbounds', { waitUntil: 'networkidle' });
await p.waitForTimeout(2500);
await p.screenshot({ path: '/tmp/ui-inbounds.png' });
const m = await b.newContext({ viewport: { width: 420, height: 900 }, deviceScaleFactor: 3, locale: 'zh-CN' });
const mp = await m.newPage();
await mp.goto('http://189.105.70.85:20000/', { waitUntil: 'networkidle' });
await mp.fill('input[autocomplete="username"]', 'eu6qSQvOwL');
await mp.fill('input[autocomplete="current-password"]', '3uplqkCMq4');
await mp.click('button[type="submit"]');
await mp.waitForTimeout(4000);
await mp.goto('http://189.105.70.85:20000/panel/inbounds', { waitUntil: 'networkidle' });
await mp.waitForTimeout(2000);
await mp.screenshot({ path: '/tmp/ui-mobile.png' });
console.log('ok');
await b.close();
