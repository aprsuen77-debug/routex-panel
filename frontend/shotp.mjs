import { chromium } from 'playwright';
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 430, height: 932 }, deviceScaleFactor: 3, locale: 'zh-CN' });
const page = await ctx.newPage();
await page.goto('http://189.105.70.85:8080/p/3bf202c4b40a343f/', { waitUntil: 'networkidle' });
await page.waitForTimeout(800);
await page.screenshot({ path: '/tmp/portal-light-mobile.png', fullPage: true });
const ctx2 = await browser.newContext({ viewport: { width: 1280, height: 900 }, deviceScaleFactor: 2, locale: 'zh-CN' });
const page2 = await ctx2.newPage();
await page2.goto('http://189.105.70.85:8080/p/3bf202c4b40a343f/', { waitUntil: 'networkidle' });
await page2.waitForTimeout(600);
await page2.screenshot({ path: '/tmp/portal-light-desktop.png', fullPage: true });
console.log('body bg:', await page2.evaluate(() => getComputedStyle(document.body).backgroundColor));
console.log('nodes:', await page2.locator('.node').count());
await browser.close();
